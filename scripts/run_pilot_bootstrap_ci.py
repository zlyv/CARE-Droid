#!/usr/bin/env python3
"""Compute bootstrap intervals for nested pilot outer-test predictions.

The input must contain predictions generated by the strict nested evaluator.
This script does not refit models and never changes thresholds.  It reports
per-year and four-year-mean intervals for the pilot result.  A paired TIF
delta interval is not possible until TIF predictions on the identical test
rows are available.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

try:
    import numpy as np
except ModuleNotFoundError as exc:  # pragma: no cover - environment dependent
    raise SystemExit("NumPy is required; use /home/boyuanjie/envs/tif/bin/python") from exc

from run_pilot_compact_eval import metrics


SCHEMA_VERSION = "1.0.0"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.expanduser().resolve(strict=True).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_csv(path: Path):
    with path.expanduser().resolve(strict=True).open(
        "r", encoding="utf-8-sig", errors="replace", newline=""
    ) as handle:
        return list(csv.DictReader(handle))


def percentile_interval(values):
    return {
        "mean": float(np.mean(values)),
        "lower_2_5": float(np.percentile(values, 2.5)),
        "upper_97_5": float(np.percentile(values, 97.5)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--predictions", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--replicates", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=20260805)
    parser.add_argument("--reference-mean", type=float, default=0.9074)
    args = parser.parse_args()

    prediction_path = args.predictions.expanduser().resolve(strict=True)
    output = args.output.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    rows = read_csv(prediction_path)
    required = {"split_name", "seed", "sha256", "y_true", "score", "threshold", "y_pred"}
    if not rows:
        raise SystemExit("prediction CSV has no rows")
    missing = sorted(required - set(rows[0]))
    if missing:
        raise SystemExit(f"prediction CSV missing columns: {missing}")

    groups = defaultdict(list)
    for row in rows:
        row = dict(row)
        row["seed"] = int(row["seed"])
        row["y_true"] = int(row["y_true"])
        row["score"] = float(row["score"])
        row["threshold"] = float(row["threshold"])
        row["y_pred"] = int(row["y_pred"])
        groups[(row["split_name"], row["seed"])].append(row)

    for key, group in groups.items():
        if len({row["threshold"] for row in group}) != 1:
            raise SystemExit(f"multiple thresholds found in prediction group: {key}")
        if len({row["sha256"] for row in group}) != len(group):
            raise SystemExit(f"duplicate SHA256 in prediction group: {key}")

    rng = np.random.RandomState(args.seed)
    metric_names = ("accuracy", "balanced_accuracy", "f1", "auc")
    group_point = {}
    bootstrap_group_values = {name: [] for name in metric_names}
    split_point_values = defaultdict(lambda: defaultdict(list))
    split_bootstrap_values = defaultdict(lambda: defaultdict(list))

    for (split_name, seed), group in sorted(groups.items()):
        y_true = np.asarray([row["y_true"] for row in group], dtype=int)
        scores = np.asarray([row["score"] for row in group], dtype=float)
        threshold = group[0]["threshold"]
        point = metrics(y_true, scores, threshold=threshold)
        group_point[(split_name, seed)] = point
        for metric_name in metric_names:
            split_point_values[split_name][metric_name].append(point[metric_name])

        for _ in range(args.replicates):
            indices = rng.randint(0, len(group), size=len(group))
            sampled = metrics(y_true[indices], scores[indices], threshold=threshold)
            for metric_name in metric_names:
                value = sampled[metric_name]
                if value is not None:
                    bootstrap_group_values[metric_name].append(value)
                    split_bootstrap_values[split_name][metric_name].append(value)

    split_summaries = []
    for split_name in sorted(split_point_values):
        summary = {"split_name": split_name}
        for metric_name in metric_names:
            point_values = split_point_values[split_name][metric_name]
            bootstrap_values = np.asarray(split_bootstrap_values[split_name][metric_name])
            summary[f"{metric_name}_point_mean"] = float(np.mean(point_values))
            summary[f"{metric_name}_ci_lower_2_5"] = float(np.percentile(bootstrap_values, 2.5))
            summary[f"{metric_name}_ci_upper_97_5"] = float(np.percentile(bootstrap_values, 97.5))
        split_summaries.append(summary)

    four_year = {}
    for metric_name in metric_names:
        # Each outer year contributes equally, and each seed contributes equally
        # within that year, matching the nested evaluator's point estimate.
        point_by_year = [summary[f"{metric_name}_point_mean"] for summary in split_summaries]
        bootstrap_by_year = []
        for replicate in range(args.replicates):
            values = []
            for split_name in sorted(split_point_values):
                start = replicate * len(groups_by_split(split_name, groups))
                group_count = len(groups_by_split(split_name, groups))
                values.append(
                    float(np.mean(split_bootstrap_values[split_name][metric_name][start:start + group_count]))
                )
            bootstrap_by_year.append(float(np.mean(values)))
        four_year[metric_name] = {
            "point_mean": float(np.mean(point_by_year)),
            "ci_lower_2_5": float(np.percentile(bootstrap_by_year, 2.5)),
            "ci_upper_97_5": float(np.percentile(bootstrap_by_year, 97.5)),
        }

    accuracy = four_year["accuracy"]
    audit = {
        "schema_version": SCHEMA_VERSION,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "phase": "P1_NESTED_PILOT_BOOTSTRAP_CI",
        "formal_training_enabled": False,
        "predictions_csv": str(prediction_path),
        "predictions_sha256": sha256_file(prediction_path),
        "prediction_row_count": len(rows),
        "outer_split_count": len(split_point_values),
        "seed_count": len({row["seed"] for row in rows}),
        "replicates": args.replicates,
        "bootstrap_seed": args.seed,
        "reference_mean": args.reference_mean,
        "reference_metric": "accuracy_mean_assumed_from_baseline_table",
        "per_split": split_summaries,
        "four_year": four_year,
        "reference_inside_accuracy_ci": bool(
            accuracy["ci_lower_2_5"] <= args.reference_mean <= accuracy["ci_upper_97_5"]
        ),
        "accuracy_ci_lower_above_reference": bool(
            accuracy["ci_lower_2_5"] > args.reference_mean
        ),
        "blocking_reasons": [
            "tif_predictions_not_available_for_paired_delta_ci",
            "audited_first_seen_utc_not_joined",
            "compact_summary_is_not_formal_graph_model",
            "resolved_formal_training_config_not_generated",
        ],
        "notes": [
            "Bootstrap resamples outer-test predictions only; it does not refit models.",
            "The reference comparison assumes the table metric is accuracy.",
            "A paired confidence interval against TIF requires TIF predictions on identical rows.",
        ],
    }
    (output / "pilot_bootstrap_audit.json").write_text(
        json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(audit, ensure_ascii=False, indent=2))


def groups_by_split(split_name, groups):
    return [key for key in groups if key[0] == split_name]


if __name__ == "__main__":
    main()
